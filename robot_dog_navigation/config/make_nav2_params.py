"""Generate nav2_params.yaml from Jazzy's nav2_bringup defaults plus robot_dog's changes (spec 6.3-6.4).

Every change from the defaults is in this file; regenerate after a Nav2 upgrade:
    python3 robot_dog_navigation/config/make_nav2_params.py
"""
import os

import yaml

NAV2 = '/opt/ros/jazzy/share/nav2_bringup/params/nav2_params.yaml'
SLAM = '/opt/ros/jazzy/share/slam_toolbox/config/mapper_params_online_async.yaml'
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'nav2_params.yaml')

FOOTPRINT = '[[0.22, 0.16], [0.22, -0.16], [-0.22, -0.16], [-0.22, 0.16]]'  # body + splayed feet (m)
LASER_MAX = 15.0  # robot_dog_sim.robot_spec.LIDAR_RANGE


def walk(node, fn):
    if isinstance(node, dict):
        for k in list(node):
            fn(node, k)
            walk(node[k], fn)
    elif isinstance(node, list):
        for v in node:
            walk(v, fn)


def common(d, k):
    if k in ('robot_base_frame', 'base_frame_id', 'base_frame', 'global_frame_id') and d[k] == 'base_link':
        d[k] = 'base_footprint'
    if k == 'use_sim_time':
        d[k] = True
    if k == 'transform_tolerance':
        d[k] = 0.5


def main():
    p = yaml.safe_load(open(NAV2))
    p.pop('loopback_simulator', None)
    walk(p, common)

    amcl = p['amcl']['ros__parameters']
    amcl.update(robot_model_type='nav2_amcl::OmniMotionModel', scan_topic='scan_filtered', laser_max_range=LASER_MAX,
                set_initial_pose=True, initial_pose={'x': 0.0, 'y': 0.0, 'z': 0.0, 'yaw': 0.0})

    ctrl = p['controller_server']['ros__parameters']
    ctrl['controller_frequency'] = 20.0
    ctrl['general_goal_checker'].update(xy_goal_tolerance=0.10, yaw_goal_tolerance=0.25)
    mppi = ctrl['FollowPath']
    # walk head first: sideways only slowly, for the last few cm at a goal (DiffDrive, with no sidestep at all, got
    # stuck 0.2-0.3 m beside a goal it had overshot); no TwirlingCritic, which made crabbing cheaper than turning;
    # small vy_std, else the samples sit at the vy limit and the dog crabs ~8 deg while cruising
    mppi.update(motion_model='Omni', vx_max=0.5, vx_min=-0.1, vy_max=0.1, vy_std=0.05, wz_max=0.8)

    for name in ('local_costmap', 'global_costmap'):
        c = p[name][name]['ros__parameters']
        c.pop('robot_radius', None)
        c['footprint'] = FOOTPRINT
        c['inflation_layer']['inflation_radius'] = 0.35
        layer = c['voxel_layer'] if 'voxel_layer' in c else c['obstacle_layer']
        layer['scan']['topic'] = '/scan_filtered'

    vs = p['velocity_smoother']['ros__parameters']
    vs.update(max_velocity=[0.5, 0.1, 0.8], min_velocity=[-0.1, -0.1, -0.8], max_accel=[1.0, 1.0, 2.0],
              max_decel=[-1.0, -1.0, -2.0], deadband_velocity=[0.0, 0.0, 0.0])

    p['collision_monitor']['ros__parameters']['scan']['topic'] = '/scan_filtered'

    slam = yaml.safe_load(open(SLAM))['slam_toolbox']['ros__parameters']
    slam.update(use_sim_time=True, base_frame='base_footprint', odom_frame='odom', map_frame='map',
                scan_topic='/scan_filtered', max_laser_range=LASER_MAX, resolution=0.05, mode='mapping')
    p['slam_toolbox'] = {'ros__parameters': slam}

    with open(OUT, 'w') as f:
        f.write('# Generated by make_nav2_params.py from Jazzy nav2_bringup + slam_toolbox defaults; edit that script.\n')
        yaml.safe_dump(p, f, sort_keys=False, default_flow_style=None, width=120)
    print('wrote', OUT)


if __name__ == '__main__':
    main()
